import {
  formatFiles,
  getProjects,
  joinPathFragments,
  MigrationReturnObject,
  Tree,
} from '@nx/devkit';

/**
 * Webpack configs that `@nx/webpack/plugin` infers a build target from.
 */
const WEBPACK_CONFIG_FILES = [
  'webpack.config.js',
  'webpack.config.cjs',
  'webpack.config.mjs',
  'webpack.config.ts',
];

const LIBRARY_COMMENT = [
  '// Forge loads function handlers from the exports of index.js, so the',
  "// bundle must assign the entry module's exports to `module.exports`.",
];
const LIBRARY_PROPERTY = "library: { type: 'commonjs2' },";

const OUTPUT_OBJECT_START = /\boutput\s*:\s*\{/g;
const LIBRARY_OPTION = /\blibrary(Target)?\s*:/;
const LINE_BREAK_AND_INDENT = /^[ \t]*(\r?\n)([ \t]*)/;
const COMMENT_OR_STRING =
  /\/\/[^\n]*|\/\*[\s\S]*?\*\/|'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\[\s\S]|[^`\\])*`/g;

/**
 * Replaces comments and string literals with spaces, so that searches only
 * match code. Line breaks are kept, so offsets match the original contents.
 */
const maskCommentsAndStrings = (contents: string): string =>
  contents.replace(COMMENT_OR_STRING, (match) => match.replace(/[^\n]/g, ' '));

const isForgeProject = (tree: Tree, root: string): boolean =>
  tree.exists(joinPathFragments(root, 'manifest.yml'));

const webpackConfigPaths = (tree: Tree, root: string): string[] =>
  WEBPACK_CONFIG_FILES.map((file) => joinPathFragments(root, file)).filter(
    (path) => tree.exists(path)
  );

/**
 * Only configs that build with `NxAppWebpackPlugin`, as generated by the
 * application generator, are affected, and only if they do not choose a
 * library type themselves.
 */
const needsLibraryOption = (code: string): boolean =>
  code.includes('NxAppWebpackPlugin') && !LIBRARY_OPTION.test(code);

/**
 * Inserts the library option as the first property of the `output` object,
 * where the application generator puts it. Returns `undefined` when the
 * config does not contain exactly one `output` object.
 */
const addLibraryOption = (
  contents: string,
  code: string
): string | undefined => {
  const matches = Array.from(code.matchAll(OUTPUT_OBJECT_START));
  if (matches.length !== 1) {
    return undefined;
  }
  const [match] = matches;
  const insertAt = (match.index ?? 0) + match[0].length;
  const rest = contents.slice(insertAt);
  const lineBreak = LINE_BREAK_AND_INDENT.exec(rest);
  const insertion = lineBreak
    ? [...LIBRARY_COMMENT, LIBRARY_PROPERTY]
        .map((line) => `${lineBreak[1]}${lineBreak[2]}${line}`)
        .join('')
    : ` ${LIBRARY_PROPERTY}`;
  return contents.slice(0, insertAt) + insertion + rest;
};

/**
 * Updates the config in place and returns its path if it has to be updated
 * by hand.
 */
const migrateWebpackConfig = (tree: Tree, path: string): string[] => {
  const contents = tree.read(path, 'utf-8') ?? '';
  const code = maskCommentsAndStrings(contents);
  if (!needsLibraryOption(code)) {
    return [];
  }
  const migrated = addLibraryOption(contents, code);
  if (migrated === undefined) {
    return [path];
  }
  tree.write(path, migrated);
  return [];
};

/**
 * Webpack bundles of Forge apps generated before 9.0.1 do not assign the
 * handler exports to `module.exports`, so every function invocation fails.
 * Set `output.library` to `commonjs2` in the Webpack config of each Forge app
 * that builds with `NxAppWebpackPlugin`.
 *
 * @see https://github.com/toolsplus/nx-forge/issues/221
 */
export default async function update(
  tree: Tree
): Promise<MigrationReturnObject | undefined> {
  const manualPaths = Array.from(getProjects(tree).values())
    .filter(({ root }) => isForgeProject(tree, root))
    .flatMap(({ root }) => webpackConfigPaths(tree, root))
    .flatMap((path) => migrateWebpackConfig(tree, path));

  await formatFiles(tree);

  return manualPaths.length > 0
    ? {
        nextSteps: [
          `Set \`output.library\` to \`{ type: 'commonjs2' }\` in these Forge app Webpack configs, otherwise the bundled functions export no handlers: ${manualPaths.join(
            ', '
          )}`,
        ],
      }
    : undefined;
}
